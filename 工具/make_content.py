def pinyin_of(text, overrides, pid, li):
    chars = list(text)
    out = []
    for i, ch in enumerate(chars):
        if ch in "，。！？、；：":
            out.append("")
            continue
        py = lazy_pinyin(ch, style=Style.TONE)[0]
        if i in overrides:
            want_ch, want_py = overrides[i]
            assert ch == want_ch, f"{pid} 句{li + 1} 第{i + 1}字错位：应为{want_ch}，实为{ch}"
            print(f"  覆盖 {pid} 句{li + 1} 第{i + 1}字 {ch}: {lazy_pinyin(ch)[0]} → {want_py}")
            py = want_py
        out.append(py)
    return out


def main():
    for p in POEMS:
        lines = []
        for li, (text, meaning) in enumerate(p["lines"]):
            lines.append({
                "text": text,
                "chars": [c for c in text],
                "pinyin": pinyin_of(text, p.get("overrides", {}).get(li, {}), p["id"], li),
                "meaning": meaning,
                "audio": f"a{li + 1}",
            })
        item = {
            "id": p["id"], "title": p["title"], "author": p["author"], "dynasty": p["dynasty"],
            "lead": p["lead"], "lines": lines, "talk": p["talk"],
            "audioFull": "afull",
            "scenes": ["s1", "s2", "s3", "s4"],
            "sticker": "sticker",
        }
        with open(os.path.join(OUT_DIR, p["id"] + ".json"), "w", encoding="utf-8") as f:
            json.dump(item, f, ensure_ascii=False, indent=2)
        print("写出", p["id"], p["title"], "".join(x["pinyin"][i] + " " for x in lines[:1] for i in range(len(x["pinyin"]))))


if __name__ == "__main__":
    main()
